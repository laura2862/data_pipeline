DECLARE
  not_exist_grant_option EXCEPTION;
  not_validated_object EXCEPTION;
  invalid_object EXCEPTION;
  v_tableName NVARCHAR2(32767) := '';
  v_error NVARCHAR2(32767) := '';
  PRAGMA EXCEPTION_INIT(not_exist_grant_option, -1720);
  PRAGMA EXCEPTION_INIT(not_validated_object, -4023);
  PRAGMA EXCEPTION_INIT(invalid_object, -40362);
begin
FOR x IN (    SELECT owner, 
						  object_name,
						  DECODE(object_type,   'TABLE',    'select, insert, update, delete',
												'SEQUENCE', 'select',
												'VIEW',     'select', 'execute'					) AS privs,
						  'E2X' AS app_user,
              object_type AS object_type
					 FROM all_objects
					WHERE object_type IN ('TABLE','PACKAGE', 'PROCEDURE','FUNCTION', 'SEQUENCE', 'VIEW')
					  AND owner       IN (SELECT userName FROM dbo.fenergoUsers)
            ORDER BY object_type, owner, object_name  ASC)
LOOP
		BEGIN
			EXECUTE IMMEDIATE 'GRANT ' || x.privs || ' on ' || x.owner || '."' || x.object_name || '" to E2X';
			IF (x.object_type IN ('TABLE','VIEW','FUNCTION')) THEN
					BEGIN
						EXECUTE IMMEDIATE 'GRANT ' || x.privs || ' ON ' || x.owner || '."' || x.object_name || '" TO E2X' ;
					EXCEPTION WHEN OTHERS THEN
						DBMS_OUTPUT.PUT_LINE(DBMS_UTILITY.format_error_stack ());
						DBMS_OUTPUT.PUT_LINE('An error occured grating privileges: '||  'GRANT ' || x.privs || ' ON ' || x.owner || '."' || x.object_name || '" TO E2X');
					END;
			END IF;
		EXCEPTION 
			WHEN not_exist_grant_option THEN
				DBMS_OUTPUT.PUT_LINE('Skipping not exist grant option: ' || x.owner || '."' || x.object_name ) ;
			WHEN not_validated_object THEN
				DBMS_OUTPUT.PUT_LINE('Skipping not validated object: ' || x.owner || '."' || x.object_name ) ;
			WHEN invalid_object THEN
				DBMS_OUTPUT.PUT_LINE('Skipping invalid object: ' || x.owner || '."' || x.object_name ) ;	
			WHEN OTHERS THEN
				DBMS_OUTPUT.PUT_LINE(DBMS_UTILITY.format_error_stack ());
				DBMS_OUTPUT.PUT_LINE('An error occured grating privileges: '||  ' GRANT ' || x.privs || ' ON ' || x.owner || '."' || x.object_name || '" TO ' || x.app_user);
		END; 
   END LOOP;
END;

