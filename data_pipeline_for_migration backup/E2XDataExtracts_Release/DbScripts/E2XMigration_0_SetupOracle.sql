CREATE OR REPLACE FORCE VIEW E2X.VWDOCUMENTS_DELETED ("ID", "LEID", "FILENAME", "LOCATION", "DOCUMENTCATEGORY", "DOCUMENTPURPOSE", "DOCUMENTTYPE", "LASTUPDATEDDATE", "ISACTIVE", "DOCUMENTDIRECTION", "DOCUMENTSTATUS", "FENXID") AS 
SELECT 
    documentData."ID"
    ,documentData."LEID"
    ,documentData."FILENAME"
    ,documentData."LOCATION"
    ,documentData."DOCUMENTCATEGORY"
    ,documentData."DOCUMENTPURPOSE"
    ,documentData."DOCUMENTTYPE"
    ,documentData."LASTUPDATEDDATE"
    ,documentData."ISACTIVE"
    ,documentData."DOCUMENTDIRECTION"
    ,documentData."DOCUMENTSTATUS"
    ,documentData."FENXDOCID"
FROM
(
    SELECT DISTINCT
        documentData."ID"
        ,documentData."LEID"
        ,documentData."FILENAME"
        ,documentData."LOCATION"
        ,documentData."DOCUMENTCATEGORY"
        ,documentData."DOCUMENTPURPOSE"
        ,documentData."DOCUMENTTYPE"
        ,documentData."LASTUPDATEDDATE"
        ,documentData."ISACTIVE"
        ,documentData."DOCUMENTDIRECTION"
        ,documentData."DOCUMENTSTATUS"
        ,DOCEX."FENXDOCID"
    FROM E2X.VWDOCUMENTS_ALL documentData
    INNER JOIN dbo.Document doc ON documentData.Id = doc.Id
    INNER JOIN dbo.LookupDocumentStatus documentStatus ON doc.LookupDocumentStatusId = documentStatus.Id
    INNER JOIN E2X.DocExportFile DOCEX ON documentData."ID" = DOCEX.FenEDocumentId
    WHERE documentstatus.Id IN (3)
    
    UNION ALL
    SELECT 
        doc.Id AS "ID"
        ,LDE.PARENTENTITYID AS "LEID"
        ,doc.Name AS "FILENAME"
        ,doc.Location AS "LOCATION"
        ,documentCategory.Name AS DOCUMENTCATEGORY
        ,documentPurpose.Name AS DOCUMENTPURPOSE
        ,documentPurpose.Name AS DOCUMENTTYPE
        ,doc.LastUpdatedDate
        ,CASE
            WHEN doc.LookupDocumentStatusId = 7 THEN '0'
            ELSE '1'
        END AS ISACTIVE
        ,'Inbound' AS DOCUMENTDIRECTION
        ,documentStatus.Name AS DOCUMENTSTATUS    
        ,DEF.FENXDOCID
    FROM E2X.DocExportFile DEF
    INNER JOIN dbo.LinkDocumentEntity LDE 
        ON DEF.FENEENTITYID = LDE.PARENTENTITYID AND DEF.FENEDOCUMENTID = LDE.DOCUMENTID AND
        LDE.BUSINESSENTITYID = 30 AND ISACTIVE = 0 AND DEF.MIGRATIONSTATUS = 'Processed' AND FENEENTITYTYPENAME = 'LegalEntity'
    LEFT JOIN dbo.Document doc ON LDE.DocumentId = doc.Id
    LEFT JOIN dbo.DocumentCategory documentCategory ON doc.DocumentCategoryId = documentCategory.Id
    LEFT JOIN dbo.DocumentPurpose documentPurpose ON doc.DocumentPurposeId = documentPurpose.Id
    LEFT JOIN dbo.DocumentType documentType ON doc.DocumentTypeId = documentType.Id
    LEFT JOIN dbo.LookupDocumentStatus documentStatus ON doc.LookupDocumentStatusId = documentStatus.Id
) documentData;


